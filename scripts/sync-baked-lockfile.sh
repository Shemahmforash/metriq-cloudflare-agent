#!/usr/bin/env bash
#
# Copy a target repo's package.json + pnpm-lock.yaml + pnpm-workspace.yaml
# into container/baked/ so the agent container Dockerfile can
# `pnpm install` those exact deps during image build (caching node_modules
# into the baked image layer).
#
# By default container/baked/ ships a generic placeholder manifest
# (name "agent-target-sample") that only pre-warms the pnpm store. Run this
# script if you operate a single well-known target repo and want the baked
# node_modules to be reused verbatim at dispatch time — point it at that
# repo via the TARGET_REPO_DIR env var (or the first argument):
#
#   TARGET_REPO_DIR=/path/to/your/repo scripts/sync-baked-lockfile.sh
#   scripts/sync-baked-lockfile.sh /path/to/your/repo
#
# The next `wrangler deploy` will pick up the changes.
#
# Stale baked deps are not fatal — the agent's entrypoint.sh runs
# `pnpm install --frozen-lockfile` against the freshly cloned target
# lockfile, which will diff-install any missing packages. Baking just makes
# the common case fast, and only when the baked lockfile byte-matches the
# cloned one.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

TARGET_REPO_DIR="${TARGET_REPO_DIR:-${1:-}}"

if [ -z "$TARGET_REPO_DIR" ]; then
  echo "error: no target repo specified." >&2
  echo "       Set TARGET_REPO_DIR=/path/to/repo or pass it as the first arg." >&2
  exit 1
fi

TARGET_REPO_DIR="$(cd "$TARGET_REPO_DIR" && pwd)"

if [ ! -f "$TARGET_REPO_DIR/package.json" ]; then
  echo "error: $TARGET_REPO_DIR/package.json not found." >&2
  echo "       Point TARGET_REPO_DIR at a repo that has a package.json." >&2
  exit 1
fi

DEST="$REPO_ROOT/container/baked"
mkdir -p "$DEST"

cp "$TARGET_REPO_DIR/package.json" "$DEST/"
cp "$TARGET_REPO_DIR/pnpm-lock.yaml" "$DEST/"
cp "$TARGET_REPO_DIR/pnpm-workspace.yaml" "$DEST/"

# Stamp the sync — useful for tracking how stale the bake is at a glance.
# Record only the repo basename (never an absolute machine path) so the
# committed stamp stays portable and discloses no local filesystem layout.
{
  echo "# Auto-generated by scripts/sync-baked-lockfile.sh — DO NOT EDIT"
  echo "# Source: $(basename "$TARGET_REPO_DIR")"
  echo "# Synced: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
} > "$DEST/SYNC_STAMP"

echo "Synced from $TARGET_REPO_DIR →"
echo "  $DEST/package.json"
echo "  $DEST/pnpm-lock.yaml"
echo "  $DEST/pnpm-workspace.yaml"
echo "  $DEST/SYNC_STAMP"
